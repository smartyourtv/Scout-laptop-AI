def generate_configs(out_dir=None, test_stream_url=TEST_STREAM_URL):
    """Write docker-compose.yml, traccar.xml, frigate config.yml under
    out_dir (default thinkpad/dvr-backend/). Returns the paths dict."""
    out_dir = out_dir or DEFAULT_OUT_DIR
    frigate_dir = os.path.join(out_dir, "frigate-config")
    os.makedirs(frigate_dir, exist_ok=True)
    paths = {
        "compose": os.path.join(out_dir, "docker-compose.yml"),
        "traccar_xml": os.path.join(out_dir, "traccar.xml"),
        "frigate_yml": os.path.join(frigate_dir, "config.yml"),
    }
    with open(paths["compose"], "w", encoding="utf-8") as f:
        f.write(docker_compose_yml())
    with open(paths["traccar_xml"], "w", encoding="utf-8") as f:
        f.write(traccar_xml())
    with open(paths["frigate_yml"], "w", encoding="utf-8") as f:
        f.write(frigate_config_yml(test_stream_url))
    return paths


# ── status / diagnostics ────────────────────────────────────────────

def _port_open(port, host="127.0.0.1", timeout=0.7):
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


def _http_status(url, timeout=2.0):
    try:
        req = urllib.request.Request(url, method="GET")
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status
    except urllib.error.HTTPError as e:
        return e.code
    except Exception:
        return None


def _docker_available():
    try:
        out = subprocess.run(["docker", "--version"], capture_output=True,
                             text=True, timeout=10)
        return out.returncode == 0, (out.stdout or out.stderr).strip()
    except Exception as e:
        return False, str(e)


def backend_status(out_dir=None):
    """Structured status with honest states. Each check distinguishes
    'config present', 'port listening', 'HTTP answering', and
    'not installed on this machine'."""
    out_dir = out_dir or DEFAULT_OUT_DIR
    docker_ok, docker_ver = _docker_available()
    checks = []

    def add(name, state, detail):
        checks.append({"name": name, "state": state, "detail": detail})

    for key, label in (("compose", "docker-compose.yml"),
                       ("traccar_xml", "traccar.xml"),
                       ("frigate_yml", "frigate config.yml")):
        paths = generate_paths(out_dir)
        add(f"config: {label}",
            "present" if os.path.exists(paths[key]) else "missing",
            paths[key])
    add("docker", "available" if docker_ok else "not installed on this machine",
        docker_ver)
    for port, label in ((TRACCAR_WEB_PORT, "Traccar web"),
                        (TRACCAR_OSMAND_PORT, "Traccar OsmAnd/GPS"),
                        (TRACCAR_JT808_PORT, "Traccar JT808"),
                        (FRIGATE_WEB_PORT, "Frigate web"),
                        (FRIGATE_RTSP_PORT, "Frigate RTSP restream")):
        add(f"port {port} ({label})",
            "listening" if _port_open(port) else "not listening",
            "no service bound (expected until Phase 1 run on ThinkPad)"
            if not _port_open(port) else "service bound")
    code = _http_status(f"http://127.0.0.1:{TRACCAR_WEB_PORT}/api/health")
    add("Traccar HTTP /api/health",
        f"HTTP {code}" if code else "no answer",
        "Traccar not running here" if not code else "Traccar answering")
    code = _http_status(f"http://127.0.0.1:{FRIGATE_WEB_PORT}/api/stats")
    add("Frigate HTTP /api/stats",
        f"HTTP {code}" if code else "no answer",
        "Frigate not running here" if not code else "Frigate answering")
    return {"docker_available": docker_ok, "checks": checks,
            "phase1_run": "NEEDS-LAPTOP (ThinkPad) — see DVR-PHASE1-HARNESS.md",
            "cutover": "GATED — Shawn go-ahead at the time; rollback "
                       f"server is {OLD_CMSV7_SERVER}"}


def generate_paths(out_dir=None):
    out_dir = out_dir or DEFAULT_OUT_DIR
    return {
        "compose": os.path.join(out_dir, "docker-compose.yml"),
        "traccar_xml": os.path.join(out_dir, "traccar.xml"),
        "frigate_yml": os.path.join(out_dir, "frigate-config", "config.yml"),
    }


def diagnostics(out_dir=None):
    st = backend_status(out_dir)
    lines = ["DVR backend (Traccar + Frigate) — diagnostics",
             f"- Docker: {'available' if st['docker_available'] else 'not installed on this machine'}"]
    for c in st["checks"]:
        lines.append(f"- {c['name']}: {c['state']} ({c['detail']})")
    lines.append(f"- Phase 1 proof run: {st['phase1_run']}")
    lines.append(f"- Cutover: {st['cutover']}")
    lines.append("- Honest note: no DVR was changed by this check. "
                 "The van DVR still points at CMSV7.")
    return "\n".join(lines)


# ── config validation (smoke mode) ──────────────────────────────────

def validate_configs(out_dir=None):
    """Validate generated config syntax. Returns [(name, ok, detail)].
    YAML: PyYAML when available, else structural checks (top-level keys,
    indentation sanity). XML: stdlib ElementTree. Compose: YAML +
    `docker compose config` when docker exists (skipped honestly)."""
    out_dir = out_dir or DEFAULT_OUT_DIR
    paths = generate_paths(out_dir)
    results = []

    def add(name, ok, detail):
        results.append((name, bool(ok), detail))

    import xml.etree.ElementTree as ET
    try:
        ET.parse(paths["traccar_xml"])
        add("traccar.xml parses as XML", True, paths["traccar_xml"])
    except Exception as e:
        add("traccar.xml parses as XML", False, str(e))

    try:
        import yaml
        have_yaml = True
    except ImportError:
        yaml = None
        have_yaml = False
    for key, label in (("frigate_yml", "frigate config.yml"),
                       ("compose", "docker-compose.yml")):
        path = paths[key]
        if not os.path.exists(path):
            add(f"{label} valid", False, "file missing — run --generate")
            continue
        text = open(path, encoding="utf-8").read()
        if have_yaml:
            try:
                data = yaml.safe_load(text)
                add(f"{label} valid YAML", isinstance(data, dict),
                    "parsed with PyYAML")
                if key == "compose":
                    services = (data or {}).get("services", {})
                    add("compose defines traccar + frigate",
                        "traccar" in services and "frigate" in services,
                        f"services={sorted(services)}")
                if key == "frigate_yml":
                    add("frigate config has test_stream camera",
                        "test_stream" in (data or {}).get("cameras", {}),
                        "Phase 1 proof camera present")
            except Exception as e:
                add(f"{label} valid YAML", False, str(e))
        else:
            ok = text.strip().startswith("#") or ":" in text
            add(f"{label} structural check (no PyYAML)", ok,
                "PyYAML not installed — full parse deferred to ThinkPad")
    docker_ok, _ = _docker_available()
    if docker_ok and os.path.exists(paths["compose"]):
        try:
            out = subprocess.run(
                ["docker", "compose", "-f", paths["compose"], "config", "-q"],
                capture_output=True, text=True, timeout=30,
                cwd=out_dir)
            add("docker compose config validates", out.returncode == 0,
                (out.stderr or out.stdout).strip()[:300])
        except Exception as e:
            add("docker compose config validates", False, str(e))
    else:
        add("docker compose config validates — SKIPPED (docker not "
            "installed on this machine; validate on the ThinkPad)", True,
            "honest skip, not a validation pass")
    return results


def self_test():
    """Smoke mode: generate configs into a temp dir, validate syntax,
    probe status honestly. Returns True when all hard checks pass."""
    import tempfile
    ok_all = True

    def check(label, cond, detail=""):
        nonlocal ok_all
        skipped = "SKIPPED" in label
        tag = "SKIP  " if skipped else ("PASS  " if cond else "FAIL  ")
        print(tag + label +
              (f"  {detail}" if detail and (not cond or skipped) else ""))
        ok_all = ok_all and bool(cond)

    with tempfile.TemporaryDirectory(prefix="dvr_backend_test_") as tmp:
        paths = generate_configs(out_dir=tmp)
        check("configs generated (compose/traccar/frigate)",
              all(os.path.exists(p) for p in paths.values()),
              str(paths))
        results = validate_configs(out_dir=tmp)
        for name, ok, detail in results:
            check(name, ok, detail)
        st = backend_status(out_dir=tmp)
        check("status reports honest not-running states",
              any(c["state"] == "not listening" for c in st["checks"])
              or st["docker_available"],
              json.dumps(st["checks"])[:200])
        check("test stream is a labelled placeholder",
              "PLACEHOLDER" in frigate_config_yml(),
              "Phase 1 run swaps in a real source on the ThinkPad")
    print("traccar_frigate self_test:",
          "ALL PASS" if ok_all else "FAILURES PRESENT")
    return ok_all


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(0 if self_test() else 1)
    if "--diagnostics" in sys.argv:
        print(diagnostics())
        sys.exit(0)
    if "--generate" in sys.argv:
        idx = sys.argv.index("--generate")
        target = sys.argv[idx + 1] if len(sys.argv) > idx + 1 else None
        made = generate_configs(out_dir=target)
        for k, v in made.items():
            print(f"{k}: {v}")
        sys.exit(0)
    if "--validate" in sys.argv:
        for name, ok, detail in validate_configs():
            print(("PASS  " if ok else "FAIL  ") + f"{name} — {detail}")
        sys.exit(0)
    print(__doc__)
